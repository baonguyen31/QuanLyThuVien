    // ── 4 KPI Cards ───────────────────────────────────────────────
    private JPanel buildKpiRow() {
        JPanel row = new JPanel(new GridLayout(1, 4, 12, 0));
        row.setOpaque(false);
        row.setMaximumSize(new Dimension(Integer.MAX_VALUE, 100));

        // [0] Tổng sách
        JPanel c1 = makeKpiCard("Tổng sách hiện có", COL_BLUE);
        lblTongSach    = getKpiValueLabel(c1);
        lblTongSachSub = getKpiSubLabel(c1);

        // [1] Phiếu mượn
        JPanel c2 = makeKpiCard("Phiếu mượn đang hoạt động", COL_TEAL);
        lblPhieuMuon    = getKpiValueLabel(c2);
        lblPhieuMuonSub = getKpiSubLabel(c2);

        // [2] Phiếu phạt
        JPanel c3 = makeKpiCard("Phiếu phạt chưa xử lý", COL_RED);
        lblPhieuPhat    = getKpiValueLabel(c3);
        lblPhieuPhatSub = getKpiSubLabel(c3);

        // [3] Độc giả
        JPanel c4 = makeKpiCard("Độc giả đang hoạt động", COL_PURPLE);
        lblDocGia    = getKpiValueLabel(c4);
        lblDocGiaSub = getKpiSubLabel(c4);

        row.add(c1); row.add(c2); row.add(c3); row.add(c4);
        return row;
    }

    private JPanel makeKpiCard(String labelText, Color accentColor) {
        JPanel card = new JPanel();
        card.setLayout(new BoxLayout(card, BoxLayout.Y_AXIS));
        card.setBackground(COL_CARD);
        card.setBorder(BorderFactory.createCompoundBorder(
            BorderFactory.createMatteBorder(0, 4, 0, 0, accentColor),
            new EmptyBorder(14, 16, 14, 16)
        ));

        JLabel lbl = new JLabel(labelText);
        lbl.setFont(new Font("Segoe UI", Font.PLAIN, 12));
        lbl.setForeground(COL_MUTED);
        lbl.setAlignmentX(Component.LEFT_ALIGNMENT);

        JLabel value = new JLabel("—");
        value.setFont(new Font("Segoe UI", Font.BOLD, 28));
        value.setForeground(accentColor);
        value.setAlignmentX(Component.LEFT_ALIGNMENT);
        value.setName("value");

        JLabel sub = new JLabel(" ");
        sub.setFont(new Font("Segoe UI", Font.PLAIN, 11));
        sub.setForeground(COL_MUTED);
        sub.setAlignmentX(Component.LEFT_ALIGNMENT);
        sub.setName("sub");

        card.add(lbl);
        card.add(Box.createVerticalStrut(4));
        card.add(value);
        card.add(Box.createVerticalStrut(2));
        card.add(sub);
        return card;
    }

    /** Lấy JLabel value từ KPI card */
    private JLabel getKpiValueLabel(JPanel card) {
        for (Component c : card.getComponents())
            if (c instanceof JLabel && "value".equals(c.getName())) return (JLabel) c;
        return new JLabel();
    }

    /** Lấy JLabel sub từ KPI card */
    private JLabel getKpiSubLabel(JPanel card) {
        for (Component c : card.getComponents())
            if (c instanceof JLabel && "sub".equals(c.getName())) return (JLabel) c;
        return new JLabel();
    }

    // ── Chart row ─────────────────────────────────────────────────
    private JPanel buildChartRow() {
        JPanel row = new JPanel(new GridBagLayout());
        row.setOpaque(false);
        row.setMaximumSize(new Dimension(Integer.MAX_VALUE, 320));

        GridBagConstraints gbc = new GridBagConstraints();
        gbc.fill    = GridBagConstraints.BOTH;
        gbc.insets  = new Insets(0, 0, 0, 0);
        gbc.weighty = 1.0;

        // Bar chart — chiếm 60%
        pnlBarChart = makeCardPanel("Top sách mượn nhiều nhất");
        gbc.gridx  = 0; gbc.weightx = 0.6;
        gbc.insets = new Insets(0, 0, 0, 6);
        row.add(pnlBarChart, gbc);

        // Pie chart — chiếm 40%
        pnlPieChart = makeCardPanel("Thống kê phiếu phạt");
        gbc.gridx  = 1; gbc.weightx = 0.4;
        gbc.insets = new Insets(0, 0, 0, 0);
        row.add(pnlPieChart, gbc);

        return row;
    }

