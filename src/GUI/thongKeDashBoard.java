    // ── Table section ─────────────────────────────────────────────
    private JPanel buildTableSection() {
        JPanel card = new JPanel(new BorderLayout(0, 10));
        card.setBackground(COL_CARD);
        card.setBorder(BorderFactory.createCompoundBorder(
            BorderFactory.createLineBorder(COL_BORDER, 1),
            new EmptyBorder(12, 14, 14, 14)
        ));
        card.setMaximumSize(new Dimension(Integer.MAX_VALUE, Integer.MAX_VALUE));

        JLabel title = new JLabel("Top sách mượn nhiều nhất");
        title.setFont(new Font("Segoe UI", Font.BOLD, 13));
        title.setForeground(COL_TEXT);
        card.add(title, BorderLayout.NORTH);

        String[] cols = {"#", "Tên sách", "Tác giả", "Thể loại", "Lượt mượn", "Còn lại", "Xu hướng"};
        tableModel = new DefaultTableModel(cols, 0) {
            @Override public boolean isCellEditable(int r, int c) { return false; }
        };

        tblTopSach = new JTable(tableModel);
        styleTable();

        JScrollPane sp = new JScrollPane(tblTopSach);
        sp.setBorder(BorderFactory.createLineBorder(COL_BORDER, 1));
        sp.getViewport().setBackground(COL_CARD);
        card.add(sp, BorderLayout.CENTER);
        return card;
    }

    private void styleTable() {
        tblTopSach.setRowHeight(36);
        tblTopSach.setFont(new Font("Segoe UI", Font.PLAIN, 13));
        tblTopSach.setGridColor(COL_BORDER);
        tblTopSach.setShowGrid(true);
        tblTopSach.setIntercellSpacing(new Dimension(0, 1));
        tblTopSach.setSelectionBackground(new Color(220, 235, 255));
        tblTopSach.setSelectionForeground(COL_TEXT);
        tblTopSach.setFillsViewportHeight(true);

        JTableHeader header = tblTopSach.getTableHeader();
        header.setFont(new Font("Segoe UI", Font.BOLD, 12));
        header.setBackground(new Color(245, 246, 250));
        header.setForeground(COL_MUTED);
        header.setPreferredSize(new Dimension(0, 36));
        header.setBorder(BorderFactory.createMatteBorder(0, 0, 1, 0, COL_BORDER));

        // Column widths
        int[] widths = {40, 220, 140, 110, 100, 80, 130};
        for (int i = 0; i < widths.length; i++)
            tblTopSach.getColumnModel().getColumn(i).setPreferredWidth(widths[i]);

        // Center align all except tên sách, tác giả
        DefaultTableCellRenderer center = new DefaultTableCellRenderer();
        center.setHorizontalAlignment(SwingConstants.CENTER);
        for (int i : new int[]{0, 4, 5}) 
            tblTopSach.getColumnModel().getColumn(i).setCellRenderer(center);

        // Xu hướng renderer (màu xanh/đỏ)
        tblTopSach.getColumnModel().getColumn(6).setCellRenderer(new DefaultTableCellRenderer() {
            @Override
            public Component getTableCellRendererComponent(JTable t, Object v,
                    boolean sel, boolean foc, int row, int col) {
                super.getTableCellRendererComponent(t, v, sel, foc, row, col);
                String val = v == null ? "" : v.toString();
                setForeground(val.startsWith("+") ? new Color(22, 101, 52) : new Color(153, 27, 27));
                setFont(new Font("Segoe UI", Font.PLAIN, 12));
                setBackground(sel ? new Color(220,235,255) : (row % 2 == 0 ? COL_CARD : COL_ROW_ALT));
                return this;
            }
        });

        // Alternating row colors
        tblTopSach.setDefaultRenderer(Object.class, new DefaultTableCellRenderer() {
            @Override
            public Component getTableCellRendererComponent(JTable t, Object v,
                    boolean sel, boolean foc, int row, int col) {
                super.getTableCellRendererComponent(t, v, sel, foc, row, col);
                setBackground(sel ? new Color(220,235,255) : (row % 2 == 0 ? COL_CARD : COL_ROW_ALT));
                setForeground(sel ? COL_TEXT : COL_TEXT);
                setBorder(new EmptyBorder(0, 8, 0, 8));
                return this;
            }
        });
    }

