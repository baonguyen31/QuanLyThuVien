    /**
     * Vẽ Bar Chart — top sách mượn nhiều.
     * @param tenSach   mảng tên sách
     * @param soLuot    mảng số lượt mượn tương ứng
     */
    public void loadBarChart(String[] tenSach, int[] soLuot) {
        DefaultCategoryDataset dataset = new DefaultCategoryDataset();
        for (int i = 0; i < tenSach.length; i++)
            dataset.addValue(soLuot[i], "Số lượt mượn", tenSach[i]);

        JFreeChart chart = ChartFactory.createBarChart(
                null, null, "Số lượt mượn", dataset
        );
        chart.setBackgroundPaint(COL_CARD);
        chart.removeLegend();

        CategoryPlot plot = chart.getCategoryPlot();
        plot.setBackgroundPaint(COL_CARD);
        plot.setOutlineVisible(false);
        plot.setRangeGridlinePaint(COL_BORDER);

        BarRenderer renderer = (BarRenderer) plot.getRenderer();
        renderer.setSeriesPaint(0, COL_BLUE);
        renderer.setDrawBarOutline(false);
        renderer.setShadowVisible(false);
        renderer.setMaximumBarWidth(0.08);

        CategoryAxis axis = plot.getDomainAxis();
        axis.setCategoryLabelPositions(CategoryLabelPositions.UP_45);
        axis.setTickLabelFont(new Font("Segoe UI", Font.PLAIN, 11));

        showChart(pnlBarChart, chart);
    }

    /**
     * Vẽ Pie Chart — thống kê phiếu phạt.
     * @param treHan    số phiếu trễ hạn
     * @param matSach   số phiếu mất sách
     * @param huHong    số phiếu hư hỏng
     */
    public void loadPieChart(int treHan, int matSach, int huHong) {
        DefaultPieDataset dataset = new DefaultPieDataset();
        dataset.setValue("Trễ hạn", treHan);
        dataset.setValue("Mất sách", matSach);
        dataset.setValue("Hư hỏng", huHong);

        JFreeChart chart = ChartFactory.createPieChart(null, dataset, true, true, false);
        chart.setBackgroundPaint(COL_CARD);

        PiePlot plot = (PiePlot) chart.getPlot();
        plot.setBackgroundPaint(COL_CARD);
        plot.setOutlineVisible(false);
        plot.setSectionPaint("Trễ hạn", COL_BLUE);
        plot.setSectionPaint("Mất sách", new Color(239, 159, 39));
        plot.setSectionPaint("Hư hỏng", new Color(93, 202, 165));
        plot.setLabelFont(new Font("Segoe UI", Font.PLAIN, 11));
        plot.setShadowPaint(null);

        showChart(pnlPieChart, chart);
    }

    /**
     * Load dữ liệu vào bảng top sách.
     * Mỗi row: [stt, tenSach, tacGia, theLoai, luotMuon, conLai, xuHuong]
     * xuHuong ví dụ: "+5 so kỳ trước" hoặc "-2 so kỳ trước"
     */
    public void loadTableTopSach(Object[][] data) {
        tableModel.setRowCount(0);
        for (Object[] row : data)
            tableModel.addRow(row);
    }

