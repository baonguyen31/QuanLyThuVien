    private void customizeTable() {
        docGiaTable.setAutoResizeMode(JTable.AUTO_RESIZE_ALL_COLUMNS);

        docGiaTable.getColumnModel().getColumn(0).setPreferredWidth(80);   // Mã dg
        docGiaTable.getColumnModel().getColumn(1).setPreferredWidth(400);  // Họ dg
        docGiaTable.getColumnModel().getColumn(2).setPreferredWidth(220);  // Tên dg
        docGiaTable.getColumnModel().getColumn(3).setPreferredWidth(200);  // SDT
        docGiaTable.getColumnModel().getColumn(4).setPreferredWidth(140);  // Địa chỉ 
        docGiaTable.getColumnModel().getColumn(5).setPreferredWidth(100);   // Trạng thái

        docGiaTable.setRowHeight(32);
        docGiaTable.setFont(new Font("Segoe UI", Font.PLAIN, 14));

        docGiaTable.getTableHeader().setFont(
                new Font("Segoe UI", Font.BOLD, 16)
        );
        docGiaTable.getTableHeader().setPreferredSize(
                new Dimension(docGiaTable.getWidth(), 40)
        );
    }

    private void loadDataSearch(ArrayList<DocGiaDTO> dsdgSearch)
    {
        Vector header = new Vector();
        header.add("Mã độc giả");
        header.add("Họ độc giả");
        header.add("Tên độc giả");
        header.add("SDT");
        header.add("Địa chỉ");
        header.add("Trạng thái");

        DefaultTableModel model = new DefaultTableModel(header, 0);
        for (DocGiaDTO docgia : dsdgSearch) {
            Vector now = new Vector();
            now.add(docgia.getMaDG());
            now.add(docgia.getHoDG());
            now.add(docgia.getTenDG());
            now.add(docgia.getSDT());
            now.add(docgia.getDiaChi());
            now.add(docgia.getTrangThai());
            model.addRow(now);

        }
        docGiaTable.setModel(model);
        customizeTable();
    }
    private void loadData() {
        DocGiaBUS docGiaBus = new DocGiaBUS();
        if (DocGiaBUS.dsdg == null) {
            docGiaBus.getALL();
        }
        Vector header = new Vector();
        header.add("Mã độc giả");
        header.add("Họ độc giả");
        header.add("Tên độc giả");
        header.add("SDT");
        header.add("Địa chỉ");
        header.add("Trạng thái");

        DefaultTableModel model = new DefaultTableModel(header, 0);
        for (DocGiaDTO docgia : DocGiaBUS.dsdg) {
            Vector now = new Vector();
            now.add(docgia.getMaDG());
            now.add(docgia.getHoDG());
            now.add(docgia.getTenDG());
            now.add(docgia.getSDT());
            now.add(docgia.getDiaChi());
            now.add(docgia.getTrangThaiString());
            model.addRow(now);

        }
        docGiaTable.setModel(model);
        customizeTable();
    }

