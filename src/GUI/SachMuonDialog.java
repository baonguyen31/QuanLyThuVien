    private void tblSachMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSachMouseClicked
        // TODO add your handling code here:
            if (evt.getClickCount() == 2) {

            int row = tblSach.getSelectedRow();

            if (row >= 0) {

                String maSach = tblSach.getValueAt(row, 0).toString();
                //        String tenDG = tb Sach.getValueAt(row, 1).toString();

                CTPhieuMuonDTO dto = new CTPhieuMuonDTO();
                dto.setMaSach(maSach);

                selectedSach = dto;

                dispose();
            }
        }
    }//GEN-LAST:event_tblSachMouseClicked
    
                 
     public void loadData(){ 
        Vector header = new Vector();
        header.add("Mã Sach");
        header.add("Tên Sach");
        header.add("Số lượng còn");
        
        DefaultTableModel model = new DefaultTableModel(header,0);
        model.setRowCount(0); //reset model 
        SachBUS sach = new SachBUS();
        for(CTPhieuMuonDTO dto : list){
        if(dto.getSoLuong() > 0) {
            Vector row = new Vector();
            row.add(dto.getMaSach());
            String tenSach = sach.getTenByMaSach(dto.getMaSach());
            row.add(tenSach);
            row.add(dto.getSoLuong());
            model.addRow(row);
        }
            
        }
            tblSach.setModel(model);
    }
     
