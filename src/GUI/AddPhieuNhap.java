    private void xoaDong(){
        btnXoa.addActionListener(e -> {
        int row = CTPNTable.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this,
                    "Vui lòng chọn dòng cần xóa");
            return;
        }

        DefaultTableModel model =(DefaultTableModel) CTPNTable.getModel();
        dsCTPN.remove(row);
        model.removeRow(row);
});
    }
    
