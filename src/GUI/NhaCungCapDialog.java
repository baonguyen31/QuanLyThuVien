    private void loadAll(){
        if(bus.dsNhaCungCap == null) list = new ArrayList<>();
        list = bus.getALL();
        loadData(list);
    }
    private void loadList(){
        String keyWord = txtTenNhaCungCap.getText().trim();
        if(keyWord.isEmpty()) list = bus.getALL();
        else {
            list = bus.searchByTenNhaCungCap(keyWord);
            
        }
        System.out.println(list.size());
         loadData(list);
    }
      
    public void loadData(ArrayList<NhaCungCapDTO> list){
        Vector header = new Vector();
        header.add("Mã NhaCungCap");
        header.add("Tên NhaCungCap");
        
        DefaultTableModel model = new DefaultTableModel(header,0);
        model.setRowCount(0); //reset model 
        
        tblNhaCungCap.setModel(model);
        for(NhaCungCapDTO dto : list){
            Vector row = new Vector();
            row.add(dto.getMaNCC());
            row.add(dto.getTenNCC());
            model.addRow(row);
            
        }
            tblNhaCungCap.setModel(model);
    }
    public NhaCungCapDTO getSelectedNhaCungCap(){
        return selectedNhaCungCap;
    }
